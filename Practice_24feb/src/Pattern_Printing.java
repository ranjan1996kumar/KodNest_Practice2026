/*Pattern Printing - Vertical Star Line
Question: Write a Java program to print a vertical line of stars (*) with exactly one star in each line, up to 5 lines.*/
public class Pattern_Printing {
	public static void main(String[] args) {
        // Write your code here
        for(int i = 0; i < 5; i++) {
            System.out.println("*");
        }
    }
}
